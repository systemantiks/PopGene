#!/usr/bin/env python3
"""Emit the pinned, licensed Biopython 1.88 / REBASE 404 catalogue as Rust data.

All original 56 indices remain stable. EcoP15I is a separately reviewed public
vendor entry; unsupported/unknown cleavage is retained explicitly, never guessed.
"""
import json
from pathlib import Path
import Bio
from Bio.Restriction.Restriction_Dictionary import rest_dict

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL = "Acc65I AcuI AflII AleI AluI ApaI AvrII BamHI BbsI BmrI BsaI BsgI BsmBI BspQI BssHII BstAPI BstEII BstZ17I Bsu36I DpnII DraI EagI EcoP15I EcoRI EcoRV FspAI HaeIII HindIII HpaII KpnI MspI NaeI NgoMIV NheI NmeAIII NotI PacI PaeR7I PaqCI PciI PfoI PmlI PshAI PspOMI PstI RsrII SalI SapI SmaI SphI SspI TaqI TaqII XbaI XcmI XhoI".split()

def main():
    assert Bio.__version__ == "1.88"
    names = ORIGINAL + sorted(set(rest_dict) - set(ORIGINAL))
    lines = [
        "// Generated by validation/generate_restriction_catalogue.py; do not edit.",
        "// Data derived from Bio.Restriction.Restriction_Dictionary, Biopython1.88 / REBASE404 (2024).",
        "// Copyright (C) 2004 Frederic Sohm; Biopython License Agreement.",
        "// Licence: vendor-notices/biopython-reference/LICENSE.rst; provenance below.",
        "pub const ENZYMES: &[Enzyme] = &[",
    ]
    for name in names:
        if name == "EcoP15I":
            site, top, bottom, second, identity, temperature = "CAGCAG", 31, 33, None, None, 37
        else:
            r = rest_dict[name]
            site, top, bottom = r["site"], r["fst5"], r["fst3"]
            if bottom is not None: bottom += r["size"]
            second = None if r["scd5"] is None else (r["scd5"], r["size"] + r["scd3"])
            identity, temperature = r["id"], r["opt_temp"]
        known = top is not None and bottom is not None
        for motif in site.split("|"):
            assert 1 <= len(motif) <= 64 and set(motif) <= set("ACGTRYSWKMBDHVN")
        second = "None" if second is None else f"Some(({second[0]}, {second[1]}))"
        identity = "None" if identity is None else f"Some({identity})"
        lines.append(f'    Enzyme {{ name: {json.dumps(name)}, recognition: {json.dumps(site)}, top_cut: {top or 0}, bottom_cut: {bottom or 0}, cleavage_known: {str(known).lower()}, second_cut: {second}, rebase_id: {identity}, catalogue_temperature_c: {temperature} }},')
    lines.append("];")
    path = ROOT / "crates/popgene-core/src/restriction_catalogue.rs"
    path.write_text("\n".join(lines) + "\n")
    print(f"Generated {len(names)} enzymes ({sum(r['fst5'] is not None for r in rest_dict.values()) + 1} with defined cleavage)")

if __name__ == "__main__": main()
