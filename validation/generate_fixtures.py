"""Create deterministic, non-biological test sequences; no third-party data."""
from pathlib import Path
import hashlib
import json
import random
import struct

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "fixtures"


def sequence(length, seed=823):
    rng = random.Random(seed)
    return "".join(rng.choice("ACGT") for _ in range(length))


def abif(include_edited=True):
    """Invented signals, with optional edited-call tags; never an experimental read."""
    entries, payload = [], bytearray()
    tags = [(b"FWO_",1,2,1,b"GATC")]
    for version in ([2,1] if include_edited else [2]):
        tags += [(b"PBAS",version,2,1,b"ACGTN"),
                 (b"PCON",version,2,1,bytes([40,35,30,20,5])),
                 (b"PLOC",version,4,2,struct.pack(">5h",2,5,8,11,14))]
    for channel,peak in [(9,8),(10,2),(11,11),(12,5)]:
        values = [0]*16
        values[peak] = 1000
        tags.append((b"DATA",channel,4,2,struct.pack(">16h",*values)))
    offset = 128 + 28*len(tags)
    for name,num,typ,size,data in tags:
        field = data.ljust(4,b"\0") if len(data)<=4 else struct.pack(">I",offset+len(payload))
        entries.append(struct.pack(">4sIHHII",name,num,typ,size,len(data)//size,len(data))+field+struct.pack(">I",0))
        if len(data)>4:
            payload.extend(data)
    root = struct.pack(">4sIHHIIII",b"tdir",1,1023,28,len(tags),28*len(tags),128,0)
    return (b"ABIF"+struct.pack(">H",101)+root).ljust(128,b"\0")+b"".join(entries)+payload


