//! Bibliographic adapters. Reference scope is original provenance, not an edited
//! feature coordinate. Cross-format attributes remain visible in REMARK/RC text.
use gb_io::seq;
use popgene_core::metadata::Reference;

pub(super) fn from_genbank(r: &seq::Reference) -> Reference {
    Reference {
        title: r.title.clone(),
        authors: r.authors.clone(),
        consortium: r.consortium.clone(),
        journal: r.journal.clone(),
        pubmed: r.pubmed.clone(),
        remark: r.remark.clone(),
        scope: (!r.description.is_empty()).then(|| r.description.clone()),
        extra: vec![],
    }
}
pub(super) fn to_genbank(r: &Reference, index: usize) -> seq::Reference {
    let mut remark = r.remark.clone().unwrap_or_default();
    for (key, value) in &r.extra {
        if !remark.is_empty() {
            remark.push(' ');
        }
        remark.push_str(&format!("{key}: {value}"));
    }
    seq::Reference {
        description: r
            .scope
            .as_ref()
            .map(|scope| {
                if let Some((a, b)) = scope.split_once('-')
                    && a.parse::<usize>().is_ok()
                    && b.parse::<usize>().is_ok()
                {
                    format!("{}  (bases {a} to {b})", index + 1)
                } else {
                    scope.clone()
                }
            })
            .unwrap_or_else(|| (index + 1).to_string()),
        title: r.title.clone(),
        authors: r.authors.clone(),
        consortium: r.consortium.clone(),
        journal: r.journal.clone(),
        pubmed: r.pubmed.clone(),
        remark: (!remark.is_empty()).then_some(remark),
    }
}

pub(super) fn read_embl(text: &str) -> Vec<Reference> {
    let mut result = vec![];
    let mut fields: Vec<(String, String)> = vec![];
    fn finish(fields: &mut Vec<(String, String)>, result: &mut Vec<Reference>) {
        if fields.is_empty() {
            return;
        }
        let mut r = Reference::default();
        for (key, value) in fields.drain(..) {
            let value = value.trim();
            match key.as_str() {
                "RN" => {} // Formatting ordinal, regenerated by the writer.
                "RT" => r.title = value.trim_end_matches(';').trim_matches('"').to_owned(),
                "RA" => r.authors = Some(value.trim_end_matches(';').to_owned()),
                "RG" => r.consortium = Some(value.trim_end_matches(';').to_owned()),
                "RL" => r.journal = Some(value.to_owned()),
                "RP" => r.scope = Some(value.to_owned()),
                "RC" => r.remark = Some(value.to_owned()),
                "RX" => {
                    if let Some((database, id)) = value.split_once(';') {
                        let id = id.trim().trim_end_matches('.').to_owned();
                        if database.trim().eq_ignore_ascii_case("PUBMED") {
                            r.pubmed = Some(id);
                        } else {
                            r.extra.push((database.trim().to_owned(), id));
                        }
                    } else {
                        r.extra.push((key, value.to_owned()));
                    }
                }
                _ => r.extra.push((key, value.to_owned())),
            }
        }
        result.push(r);
    }
    for line in text.lines().take_while(|line| {
        !line.starts_with("FH") && !line.starts_with("FT") && !line.starts_with("SQ")
    }) {
        let Some(key) = line.get(..2) else {
            continue;
        };
        if !matches!(key, "RN" | "RA" | "RG" | "RT" | "RL" | "RP" | "RC" | "RX") {
            continue;
        }
        if key == "RN" {
            finish(&mut fields, &mut result);
        }
        let Some(value) = line.get(5..) else {
            continue;
        };
        if key != "RX"
            && let Some((previous, content)) = fields.last_mut()
            && previous == key
        {
            content.push(' ');
            content.push_str(value);
        } else {
            fields.push((key.into(), value.into()));
        }
    }
    finish(&mut fields, &mut result);
    result
}

pub(super) fn write_embl(output: &mut String, refs: &[Reference]) {
    use super::embl::field;
    for (index, r) in refs.iter().enumerate() {
        field(output, "RN", &format!("[{}]", index + 1));
        // INSDC GenBank scope includes a reference ordinal and parentheses;
        // EMBL RP stores only ranges. Only map the well-defined simple form.
        if let Some(scope) = &r.scope {
            let mapped = scope
                .split_once("(bases ")
                .and_then(|(_, s)| s.strip_suffix(')'))
                .map(|s| s.replace(" to ", "-"));
            if scope
                .bytes()
                .all(|b| b.is_ascii_digit() || b"-;, ".contains(&b))
                && scope.contains('-')
            {
                field(output, "RP", scope);
            } else if let Some(mapped) = mapped {
                field(output, "RP", &mapped);
            } else {
                field(output, "RC", &format!("Original reference scope: {scope}"));
            }
        }
        if let Some(v) = &r.authors {
            field(output, "RA", &format!("{};", v.trim_end_matches(';')));
        }
        if let Some(v) = &r.consortium {
            field(output, "RG", &format!("{};", v.trim_end_matches(';')));
        }
        field(output, "RT", &format!("\"{}\";", r.title));
        if let Some(v) = &r.journal {
            field(output, "RL", v);
        }
        if let Some(v) = &r.pubmed {
            field(output, "RX", &format!("PUBMED; {v}."));
        }
        if let Some(v) = &r.remark {
            field(output, "RC", v);
        }
        for (k, v) in &r.extra {
            if matches!(k.as_str(), "DOI" | "MEDLINE" | "AGRICOLA") {
                field(output, "RX", &format!("{k}; {v}."));
            } else {
                field(output, "RC", &format!("{k}: {v}"));
            }
        }
        output.push_str("XX\n");
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn references_survive_edits_and_standard_format_conversion() {
        let text=b"LOCUS       synthetic 12 bp DNA linear UNK 01-JAN-2000\nREFERENCE   1  (bases 1 to 12)\n  AUTHORS   Example,A.\n  CONSRTM   Example consortium\n  TITLE     Synthetic citation\n  JOURNAL   Example Journal 1, 2 (2026)\n   PUBMED   12345678\n  REMARK    Synthetic bibliographic metadata\nORIGIN\n        1 aaacccgggttt\n//\n";
        let mut doc = crate::import("refs.gb", text).unwrap();
        assert_eq!(doc.references.len(), 1);
        doc.description = "Edited".into();
        let gb = crate::genbank_bytes(&doc).unwrap();
        let restored = crate::import("edited.gb", &gb).unwrap();
        assert_eq!(restored.references, doc.references);
        let embl = crate::embl::write(&doc).unwrap();
        let mut restored = crate::import("edited.embl", &embl).unwrap();
        assert_eq!(restored.references[0].title, doc.references[0].title);
        assert_eq!(restored.references[0].authors, doc.references[0].authors);
        assert_eq!(
            restored.references[0].consortium,
            doc.references[0].consortium
        );
        assert_eq!(restored.references[0].pubmed, doc.references[0].pubmed);
        assert_eq!(restored.references[0].remark, doc.references[0].remark);
        restored.description = "Edited twice".into();
        let embl2 = crate::embl::write(&restored).unwrap();
        assert_eq!(
            crate::import("again.embl", &embl2).unwrap().references,
            restored.references
        );
    }
    #[test]
    fn embl_doi_and_wrapped_reference_fields_remain_structured() {
        let refs = read_embl(
            "RN   [1]\nRX   DOI; 10.1000/synthetic.\nRX   PUBMED; 1234.\nRA   Example A.,\nRA   Another B.;\nRT   \"A synthetic\nRT   citation\";\nRL   Unpublished.\n",
        );
        assert_eq!(refs[0].title, "A synthetic citation");
        assert_eq!(refs[0].authors.as_deref(), Some("Example A., Another B."));
        assert_eq!(
            refs[0].extra,
            vec![("DOI".into(), "10.1000/synthetic".into())]
        );
    }
}

#[cfg(test)]
mod style_tests {
    #[test]
    fn published_styles_keep_each_position_in_standard_formats() {
        let mut doc = crate::import(
            "styles.gb",
            include_bytes!("../../../validation/fixtures/regression/annotation-styles.gb"),
        )
        .unwrap();
        let expected = doc.features[0].display_segments();
        assert_eq!(doc.features[0].len(), 50);
        assert_eq!(doc.features[0].display_cleavage_sites(), vec![30, 65, 80]);
        assert_eq!(doc.features[0].display_gaps().len(), 1);
        doc.description = "Edited metadata".into();
        for format in [crate::SaveFormat::GenBank, crate::SaveFormat::Embl] {
            let bytes = crate::encode(&doc, format).unwrap();
            let imported = crate::import("styles", &bytes).unwrap();
            assert_eq!(imported.features[0].display_segments(), expected);
            assert_eq!(
                imported.features[0].display_cleavage_sites(),
                vec![30, 65, 80]
            );
            assert_eq!(imported.features[1].location, doc.features[1].location);
        }
        assert!(
            crate::encode(&doc, crate::SaveFormat::SnapGene)
                .unwrap_err()
                .to_string()
                .contains("line appearance")
        );
    }
}
